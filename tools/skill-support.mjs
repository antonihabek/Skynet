#!/usr/bin/env node
/**
 * `docs/skill-support.md` — which of the Hub's skills reach, start on and run on which bodies (DRY-COVERAGE-PLAN.md item 12.F.8).
 *
 * The page is generated from `reference/reports/fleet.json`: its `skills` block (the library the `skill` stage ran against) and every
 * row's `skill` stage (`fleet/sweep.py --stage skill`). It is generated so that it cannot say more than the stage measured, and
 * `--check` is how that is held:
 *
 * 1. **The page is the report.** The committed page must equal what this prints from the committed report.
 * 2. **`verified_on` names only a row that ran.** The field is defined as "robot slugs the publisher has actually verified". A skill may
 *    name a body there only if the report shows that skill driven through the kernel loop on that body's row *clean*; a name that no
 *    row backs is a claim nobody ran, and the check says which.
 * 3. **The report is the library.** With the Hub beside this checkout, each manifest's id, version and `verified_on` must be what the
 *    report recorded. A skill that changed since the stage ran makes the page stale, and the check says to run the stage again; without
 *    the Hub it says it did not measure that, rather than passing.
 *
 *   node tools/skill-support.mjs            # write docs/skill-support.md
 *   node tools/skill-support.mjs --check    # fail when the page, the report or the library disagree
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { findHub } from './hub-path.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PAGE = join(ROOT, 'docs', 'skill-support.md')
const report = JSON.parse(readFileSync(join(ROOT, 'reference', 'reports', 'fleet.json'), 'utf8'))

const library = report.skills ?? []
const names = (text) => (typeof text === 'string' && text !== '' ? text.split(', ') : [])
const reached = report.robots.filter((row) => row.stages?.loop?.outcome === 'pass')
const staged = reached.filter((row) => row.stages?.skill && row.stages.skill.outcome !== 'not_run')

/** Per skill, how many bodies each question was answered yes for. */
function tally(name) {
  const count = { binds: 0, names: 0, supplied: 0, starts: 0, clean: 0, clamped: 0, host_refused: 0, failed: 0 }
  for (const row of staged) {
    const stage = row.stages.skill
    for (const key of ['binds', 'names', 'supplied', 'starts', 'clean']) if (names(stage[key]).includes(name)) count[key] += 1
    for (const key of ['clamped', 'host_refused', 'failed']) if (stage[key] && name in stage[key]) count[key] += 1
  }
  return count
}

const label = (row) => `${row.maker} ${row.model}`
const pad = (value) => String(value)

function render() {
  const lines = []
  const out = (text = '') => lines.push(text)
  const total = staged.length
  out('# Skill support')
  out()
  out('> Generated by `node tools/skill-support.mjs` from `reference/reports/fleet.json`. Do not edit it by hand; `--check` fails when it differs.')
  out()
  out(
    `This page says which of the Hub's ${library.length} skills **reach**, **start on** and **run on** which bodies, as far as a dry test can. ` +
      `It is the skill half of the fleet sweep: ${total} public robot descriptions that reached the kernel loop, each asked of every skill. ` +
      '**It is not a statement that any skill works on any robot.** Nothing here was run on hardware, no skill has been judged `success` by the daemon (§54.3) on any body, ' +
      'and a taught pose that lies inside a body\'s limits is the pose of the body it was taught on, not the pose the task needs.',
  )
  out()
  out('## 1. What is asked of each skill on each body')
  out()
  out('| Question | Where it is answered | A "no" means |')
  out('|---|---|---|')
  out('| **binds** | `skynet skill check --body` → `skill.transport.resolves` | no channel of the skill\'s action space has an equivalent here (§6, §37.1) — or, for a hand, this body declares none |')
  out('| **names** | `skill.context.on_body` | a clause names a joint this body does not have, so §54.2\'s first rule refuses it with the path named |')
  out('| **supplied** | `skill.context.supplied` | a clause reads a path the daemon never fills — today `robot.state.gripper` (`docs/issues/gripper-has-no-open-end.md`) — so the skill never starts on *any* robot |')
  out('| **starts** | all three | the skill\'s preconditions can be evaluated here |')
  out('| **driven** | the skill\'s own `bin/run` through `skynetk --source` on the body | `clean`: every taught row fired, none refused, nothing clamped. `clamped`: every row fired and the kernel clamped some commands (a taught angle past this body\'s limit). `host refused`: the kernel host will not execute the plan (F218). `failed`: anything else, with the reason in the report |')
  out()
  out("A hand: the MuJoCo driver declares no end effector (it will not guess a hand from a joint's name), so the sweep, acting as the integrator who accepts a role table (§63.4), declares one — on two grounds, in this order: a joint carries the very role the skill's `gripper` channel names (*by role*), or the body has a joint of exactly the name the skill gives its own gripper joint (*by name*, the rule the planner applies to every other channel). It is recorded on the row (`declared_hand`), and it is the sweep's word, not the scene's. A joint that merely resembles a hand — `Jaw`, `gripper_joint_1` — is not declared.")
  out()
  out(`## 2. The library (${library.length} skills)`)
  out()
  out('| Skill | Taught on | Taught rows | Card seconds | `verified_on` |')
  out('|---|---|---:|---:|---|')
  for (const skill of library) {
    out(`| \`${skill.name}\` | ${skill.source ? `\`${skill.source}\`` : '— (commands nothing)'} | ${skill.commands ? skill.rows : '—'} | ${skill.seconds ?? '—'} | ${skill.verified_on.length ? skill.verified_on.map((s) => `\`${s}\``).join(', ') : '*none — no run backs one*'} |`)
  }
  out()
  out(`## 3. Across the fleet (${total} bodies that reached the kernel loop)`)
  out()
  out('| Skill | binds | names | supplied | **starts** | clean | clamped | host refused | failed |')
  out('|---|---:|---:|---:|---:|---:|---:|---:|---:|')
  const sums = { binds: 0, names: 0, supplied: 0, starts: 0, clean: 0, clamped: 0, host_refused: 0, failed: 0 }
  for (const skill of library) {
    const count = tally(skill.name)
    for (const key of Object.keys(sums)) sums[key] += count[key]
    out(`| \`${skill.name}\` | ${pad(count.binds)} | ${pad(count.names)} | ${pad(count.supplied)} | **${pad(count.starts)}** | ${pad(count.clean)} | ${pad(count.clamped)} | ${pad(count.host_refused)} | ${pad(count.failed)} |`)
  }
  out(`| *all skills* | ${sums.binds} | ${sums.names} | ${sums.supplied} | **${sums.starts}** | ${sums.clean} | ${sums.clamped} | ${sums.host_refused} | ${sums.failed} |`)
  out()
  // Asked in order, each pair is counted once, at the first question it fails.
  const first = { binds: 0, names: 0, supplied: 0, starts: 0 }
  for (const row of staged) {
    const stage = row.stages.skill
    const binds = new Set(names(stage.binds))
    const named = new Set(names(stage.names))
    const supplied = new Set(names(stage.supplied))
    for (const skill of library) {
      if (!binds.has(skill.name)) first.binds += 1
      else if (!named.has(skill.name)) first.names += 1
      else if (!supplied.has(skill.name)) first.supplied += 1
      else first.starts += 1
    }
  }
  out(
    `Of ${library.length * total} (skill, body) pairs, **${first.starts} start**. Asked in the order above, each pair is counted once, at the first question it fails: ` +
      `**${first.binds}** do not bind (no equivalent channel, or no hand); **${first.names}** bind and then name a joint the body does not have; ` +
      `**${first.supplied}** bind and name its joints and then read a path the daemon does not fill.`,
  )
  out()
  const fills = staged.filter((row) => names(row.stages.skill.starts).length > 0)
  out(`Bodies on which at least one skill starts: **${fills.length}**${fills.length ? ` (${fills.map((row) => `\`${row.id}\``).join(', ')})` : ''}.`)
  out()
  out('## 4. Where a taught path ran')
  out()
  const hostRefusals = new Map()
  for (const row of staged) {
    for (const why of Object.values(row.stages.skill.host_refused ?? {})) hostRefusals.set(why, (hostRefusals.get(why) ?? 0) + 1)
  }
  const ran = staged.filter((row) => names(row.stages.skill.clean).length + Object.keys(row.stages.skill.clamped ?? {}).length + Object.keys(row.stages.skill.failed ?? {}).length > 0)
  if (ran.length === 0) {
    out("No skill's taught path was driven through the kernel loop on any body.")
  } else {
    out(`The kernel host drove a skill's own \`bin/run\` on **${ran.length}** bodies:`)
    out()
    out('| Body | Description | Declared hand | Clean | Clamped | Failed |')
    out('|---|---|---|---:|---:|---:|')
    for (const row of ran) {
      const stage = row.stages.skill
      out(`| \`${row.id}\` | ${label(row)} | ${stage.declared_hand ?? '—'} | ${names(stage.clean).length} | ${Object.keys(stage.clamped ?? {}).length} | ${Object.keys(stage.failed ?? {}).length} |`)
    }
  }
  out()
  if (hostRefusals.size > 0) {
    out('Everywhere else the planner binds and the host will not execute the plan. `skynet-kernel-host/src/plan.rs` writes channel *i* to joint *i* and commands every joint on every cycle (§93.2: *it has no channel map*), so a plan that reorders joints or leaves one out is refused the rings (F218, `docs/issues/planner-holds-what-the-host-refuses.md`). Pairs refused: ' +
      [...hostRefusals].map(([why, count]) => `**${why}**: ${count}`).join('; ') + '.')
    out()
  }
  const clamps = staged.flatMap((row) => Object.entries(row.stages.skill.clamped ?? {}).map(([name, why]) => ({ row, name, why })))
  if (clamps.length > 0) {
    out('### Taught paths the kernel clamped')
    out()
    out('| Body | Skills | The first, and what the kernel did |')
    out('|---|---:|---|')
    const byBody = new Map()
    for (const { row, name, why } of clamps) {
      const entry = byBody.get(row.id) ?? { count: 0, first: `\`${name}\`: ${why}` }
      entry.count += 1
      byBody.set(row.id, entry)
    }
    for (const [id, { count, first }] of byBody) out(`| \`${id}\` | ${count} | ${first} |`)
    out()
  }
  const exceeding = staged.flatMap((row) => Object.entries(row.stages.skill.exceeds ?? {}).map(([name, why]) => ({ row, name, why })))
  out("### Taught angles that exceed a body's travel")
  out()
  out("Found from the transport plan, without running the loop: each binding's taught column against the travel the plan holds for the joint it bound (§92). This is what the kernel would clamp, and it holds for the bodies the host will not run a plan on.")
  out()
  if (exceeding.length === 0) {
    out('None: no taught path asks a bound joint past its travel on any body.')
  } else {
    const perSkill = new Map()
    for (const { name } of exceeding) perSkill.set(name, (perSkill.get(name) ?? 0) + 1)
    out(`**${exceeding.length}** (skill, body) pairs: ` + [...perSkill].sort((x, y) => y[1] - x[1] || x[0].localeCompare(y[0])).map(([name, count]) => `\`${name}\` on ${count}`).join(', ') + '.')
    out()
    out('| Body | Skills past its travel | Example |')
    out('|---|---:|---|')
    const perBody = new Map()
    for (const { row, name, why } of exceeding) {
      const entry = perBody.get(row.id) ?? { count: 0, example: `\`${name}\`: ${why}` }
      entry.count += 1
      perBody.set(row.id, entry)
    }
    for (const [id, { count, example }] of perBody) out(`| \`${id}\` | ${count} | ${example} |`)
  }
  out()
  out('## 5. `verified_on`')
  out()
  out('The Hub defines `verified_on` as *robot slugs the publisher has actually verified, not the ones they hope work*. This page is the only place a slug may come from: ' +
    'a skill may name a body there only if its row above shows that skill driven **clean** on it. `node tools/skill-support.mjs --check` refuses a name no row backs.')
  out()
  out('## 6. What this cannot say, and does not try to')
  out()
  out('* **That a skill succeeds.** `success_criteria` are judged by the daemon over a state this sweep does not hold (§54.3). A `clean` run means the taught table was executed as published, with nothing refused and nothing clamped; it does not mean the arm reached the pose.')
  out('* **That a pose is right on another body.** A taught angle is a measurement of a cell and a body (`docs/issues/skill-clauses-name-one-bodys-joints.md`). A body whose limits contain the number is a body that will execute it, not one that will do the task.')
  out('* **Grip force, perception, the physical world.** The sweep drives MuJoCo bodies with no gripper physics worth the name and no objects. 12.F.9 records these as physical-only.')
  out('* **Any body not in the fleet.** The page quantifies the public robot descriptions in `fleet/catalogue.json`; a body absent from it is not "unsupported", it is unmeasured.')
  out()
  return lines.join('\n') + '\n'
}

function failures() {
  const problems = []
  if (library.length === 0) problems.push('the fleet report has no `skills` block: run `python3 fleet/sweep.py --stage skill` with the Hub\'s skills')
  if (staged.length === 0 && library.length > 0) problems.push('no row of the fleet report has a skill stage')
  const rows = new Map(report.robots.map((row) => [row.id, row]))
  for (const skill of library) {
    for (const slug of skill.verified_on) {
      const row = rows.get(slug)
      if (!row) problems.push(`${skill.name}: verified_on names \`${slug}\`, which is not a row of the fleet report`)
      else if (!names(row.stages?.skill?.clean).includes(skill.name)) problems.push(`${skill.name}: verified_on names \`${slug}\`, and no run of that skill on that body was clean`)
    }
  }
  const hub = findHub(ROOT)
  const directory = hub ? join(hub, 'skynet-skills', 'skills') : null
  if (directory && existsSync(directory)) {
    const live = new Map()
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name, 'manifest.json')
      if (entry.isDirectory() && existsSync(path)) live.set(entry.name, JSON.parse(readFileSync(path, 'utf8')))
    }
    const recorded = new Map(library.map((skill) => [skill.name, skill]))
    for (const name of new Set([...live.keys(), ...recorded.keys()])) {
      const now = live.get(name)
      const then = recorded.get(name)
      if (!now) problems.push(`${name} is in the report and not in the Hub's library any more: run the stage again`)
      else if (!then) problems.push(`${name} is in the Hub's library and not in the report: run the stage again`)
      else if (now.version !== then.version || JSON.stringify(now.embodiment?.verified_on ?? []) !== JSON.stringify(then.verified_on)) {
        problems.push(`${name}: the Hub's manifest (version ${now.version}, verified_on ${JSON.stringify(now.embodiment?.verified_on ?? [])}) is not the one the stage ran against (version ${then.version}, verified_on ${JSON.stringify(then.verified_on)}): run the stage again`)
      }
    }
    return { problems, measuredHub: true }
  }
  return { problems, measuredHub: false }
}

const check = process.argv.includes('--check')
const text = render()
if (!check) {
  writeFileSync(PAGE, text)
  console.log(`skill-support: wrote ${PAGE} (${library.length} skills, ${staged.length} bodies)`)
  process.exit(0)
}
const { problems, measuredHub } = failures()
const current = existsSync(PAGE) ? readFileSync(PAGE, 'utf8').replace(/\r\n/g, '\n') : ''
if (current !== text) problems.push('docs/skill-support.md is not what `node tools/skill-support.mjs` prints from reference/reports/fleet.json: regenerate it')
if (problems.length) {
  for (const problem of problems) console.error(`skill-support: ${problem}`)
  process.exit(1)
}
console.log(
  `skill-support: ${library.length} skills over ${staged.length} bodies; the page is the report` +
    (measuredHub ? ', and the report is the Hub\'s library' : ' (the Hub is not beside this checkout, so the library was not compared with it)'),
)
