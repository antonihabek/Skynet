/**
 * Provenance classes for on-robot evaluation results (§56).
 *
 * §56.1 states the problem in one sentence and the whole design follows from it:
 *
 * > **A leaderboard fed by self-reported on-robot numbers is trivially gameable** — a publisher
 * > evaluating their own policy on their own robot, choosing their own seeds, and reporting their
 * > own score is not producing evidence.
 * >
 * > So an on-robot evaluation result is only worth as much as its attestation.
 *
 * This module is *"only worth as much as its attestation"* made mechanical. It takes a run bundle
 * and the benchmark it claims to be a run of, and returns one of §56.2's three classes plus the
 * reasons — because *"this is not a field result"* and *"and here is which of the four conditions
 * failed"* are different amounts of help, and the second is the one a publisher can act on.
 *
 * ── The three classes, and why the worst one is accepted ────────────────────
 *
 * | Class | Means | Leaderboard |
 * |---|---|---|
 * | `field` | A real robot, valid birth certificate, attested image, non-simulator driver | Eligible |
 * | `simulated` | A simulator RHAL driver, which must declare itself | Eligible, separately ranked |
 * | `unattested` | No device signature, or a device the Hub does not know | **Accepted and never ranked** |
 *
 * §56.2: *"`unattested` is accepted rather than refused because a researcher on a bench robot has
 * a legitimate result worth recording — and it is never ranked, because it is not evidence."*
 *
 * That distinction — **recorded** and **not ranked** — is the whole posture, and it is the same
 * one §51 takes about entitlement and §5 takes about unsigned descriptors: the platform stores
 * what it was given and refuses to *call* it something it has not established.
 *
 * ── The order of the checks is the anti-gaming argument ─────────────────────
 *
 * Only one of the three classes is worth lying to obtain, and it is `field`. So:
 *
 * 1. **An untrustworthy device signature is `unattested`, before anything else is looked at.** A
 *    bundle nobody can attribute makes claims about its own simulator flag, its own seeds and its
 *    own birth certificate, and none of those claims is evidence either.
 * 2. **A declared simulator is `simulated`, and can never be `field`.** §35.3 puts the obligation
 *    to declare on the driver, and this is the point at which that obligation pays: a simulator
 *    that reached the field leaderboard would be the single result the whole scheme exists to
 *    prevent.
 * 3. **`field` requires all four of its conditions**, and a bundle that meets three of them is
 *    `unattested` rather than a fourth class. It has not established that it is a field result,
 *    which is exactly what `unattested` means.
 *
 * ── Seeds (§56.3) ───────────────────────────────────────────────────────────
 *
 * > `BenchmarkManifest.seeds` is supplied to the robot, never generated by it. A robot that picks
 * > its own seeds picks easy ones, and it need not do so dishonestly — an autocorrelated PRNG and
 * > a convenient starting pose is enough.
 *
 * "Supplied, never generated" is a sentence about a protocol. Its mechanical form is that the
 * seeds in the bundle must be the benchmark's, in the benchmark's order, and a run whose seeds
 * differ is not a run of that benchmark — so it cannot be ranked against it.
 *
 * ── Pure ────────────────────────────────────────────────────────────────────
 *
 * No clock, no key, no database. The device signature arrives decided, as everywhere else here,
 * and whether the Hub recognises the device is a boolean the Hub supplies. That is what lets the
 * Hub classify a submitted bundle and a robot predict its own class offline, by one function.
 */

import type { SignatureState } from './package.ts'

/** A run bundle, as §56.2 lists it. */
export interface RunBundle {
  /** The benchmark this claims to be a run of. */
  benchmark_digest: string
  /** The policy that ran. */
  policy_digest: string
  /** The body it ran on. */
  embodiment_digest: string
  /** The OS image it ran under. */
  os_image_digest: string
  /** The seeds actually used. §56.3: supplied by the benchmark, never chosen by the robot. */
  seeds: string[]
  /**
   * A hash of the black box segment covering the run (§56.4).
   *
   * What makes a disputed result **replayable** rather than arguable, and §56.4 calls it *"the
   * strongest argument for the whole black box subsystem existing."* Its absence does not change
   * the class — a result can be perfectly attested and unreplayable — but it is reported, because
   * a number with a recording behind it is a different class of claim from a number.
   */
  blackbox_segment?: string | null
  /** The tier the robot was in at run time. */
  tier: string
  /** The enforcement mode at run time. */
  enforcement: string
  /** Whether the RHAL driver declared itself a simulator (§35.3, §70). */
  simulator: boolean
  /** What the Hub concluded about the device's signature over this bundle. */
  device_signature: SignatureState
  /**
   * Whether the Hub recognises the device that signed it.
   *
   * Separate from the signature state, and §56.2 names both in one row for a reason: a signature
   * can verify perfectly and be made by a device nobody registered. Neither is evidence alone.
   */
  device_known: boolean
  /**
   * Whether the robot's birth certificate attests it (§50).
   *
   * Supplied rather than recomputed here: it is `birth.attests`, and duplicating that decision
   * would give the platform two answers to one question.
   */
  birth_attested: boolean
  /** Whether the running OS image was attested at check-in. */
  image_attested: boolean
}

/**
 * §56.2's classes, ordered strongest to weakest.
 *
 * Not sorted: the order is the ranking, and an edition that sorted these alphabetically would put
 * `field` after `unattested`.
 */
export const PROVENANCE_CLASSES = ['field', 'simulated', 'unattested'] as const

export type Provenance = (typeof PROVENANCE_CLASSES)[number]

/** Whether a result of this class appears on a leaderboard at all. */
export function rankable(provenance: Provenance): boolean {
  return provenance === 'field' || provenance === 'simulated'
}

/**
 * Whether it is ranked in its own table rather than against field results.
 *
 * §56.2 says *"eligible, separately ranked"* and the separation is not a courtesy. A simulated run
 * and a field run are not comparable numbers, and putting them in one table would make the
 * leaderboard a worse instrument than no leaderboard.
 */
export function rankedSeparately(provenance: Provenance): boolean {
  return provenance === 'simulated'
}

/** Every reason code a classification can carry. */
export const PROVENANCE_REASON_CODES = [
  'device_signature',
  'device_unknown',
  'simulator_declared',
  'birth_unattested',
  'image_unattested',
  'seeds_not_supplied',
  'benchmark_mismatch',
  'not_replayable',
] as const

export type ProvenanceReasonCode = (typeof PROVENANCE_REASON_CODES)[number]

/**
 * Why a bundle is not what it might have been.
 *
 * `subjects` carries whatever the reason is about, and the ordering rule is the one `birth` uses:
 * **what was expected, then what was supplied**, never the reverse.
 *
 * | Code | `subjects` |
 * |---|---|
 * | `device_signature` | the signature state |
 * | `seeds_not_supplied` | how many the benchmark supplies, then how many were used |
 * | `benchmark_mismatch` | the benchmark being ranked against, then the one named |
 * | everything else | empty |
 *
 * `seeds_not_supplied` carries the two **counts** rather than the two lists, which is what its
 * sentence reads and what a flat array of strings can hold without a separator that a seed could
 * collide with. Nothing is lost: a consumer that wants the seeds already holds both the bundle and
 * the manifest they came from.
 */
export interface ProvenanceReason {
  code: ProvenanceReasonCode
  subjects: string[]
}

/**
 * Whether this reason is why the bundle cannot be `field`.
 *
 * Everything except `not_replayable`: a result can be perfectly attested and unreplayable.
 */
export function blocksField(reason: ProvenanceReason): boolean {
  return reason.code !== 'not_replayable'
}

/** The sentence a publisher gets. */
export function explain(reason: ProvenanceReason): string {
  switch (reason.code) {
    case 'device_signature':
      return `The device's signature over this bundle is ${reason.subjects[0] ?? ''}, so nothing `
        + 'in it is attributable to a machine. The result is recorded and is not ranked: a number '
        + 'nobody can attribute is not evidence, which is the whole of §56.1.'
    case 'device_unknown':
      return 'The signature verifies and this Hub does not know the device that made it. Nothing '
        + 'is wrong with the bytes; what is missing is a registered machine to attribute them to. '
        + 'Register the device, then re-submit.'
    case 'simulator_declared':
      return 'The RHAL driver declared itself a simulator (§35.3), so this is a simulated result '
        + 'and is ranked on the simulated table. This is the driver meeting its obligation rather '
        + 'than a fault — and a simulated run and a field run are not comparable numbers, which '
        + 'is why the tables are separate.'
    case 'birth_unattested':
      return 'This robot\'s birth certificate does not attest it (§50), so "a real robot of this '
        + 'model with these joint ratings" is a claim the machine makes about itself. The result '
        + 'is recorded and not ranked as a field result.'
    case 'image_unattested':
      return 'The OS image running during this evaluation was not attested, so what produced '
        + 'these numbers is not established. Recorded, not ranked as a field result.'
    case 'seeds_not_supplied':
      // The counts rather than the seeds: a benchmark can carry hundreds, and a sentence that
      // pasted both lists would be one nobody reads.
      return `This run used seeds the benchmark did not supply (${reason.subjects[0] ?? ''} given, `
        + `${reason.subjects[1] ?? ''} used). §56.3: seeds come from the benchmark and are never `
        + 'generated by the robot, because a robot that picks its own seeds picks easy ones — and '
        + 'it need not do so dishonestly for the number to be worthless. This is not a run of that '
        + 'benchmark.'
    case 'benchmark_mismatch':
      return `This bundle is a run of benchmark ${reason.subjects[1] ?? ''} and is being ranked `
        + `against ${reason.subjects[0] ?? ''}. Two benchmarks are two questions, and a score `
        + 'against one says nothing about the other.'
    case 'not_replayable':
      return 'No black box segment accompanies this run, so a disputed result cannot be replayed '
        + '(§56.4). The class is unaffected — a result can be perfectly attested and unreplayable '
        + '— but a number with a recording behind it is a different class of claim from a number '
        + 'in a table.'
  }
}

/** What classifying one bundle concluded. */
export interface Classified {
  /** The class §56.2 assigns. */
  class: Provenance
  /** Everything that kept it out of a better class, plus anything else worth saying. */
  reasons: ProvenanceReason[]
}

/** Whether the run can be replayed from its recording (§56.4). */
export function replayable(classified: Classified): boolean {
  return !classified.reasons.some(reason => reason.code === 'not_replayable')
}

function sameSeeds(a: string[], b: readonly string[]): boolean {
  return a.length === b.length && a.every((seed, index) => seed === b[index])
}

/**
 * Classify a run bundle against the benchmark it claims to be a run of (§56.2).
 *
 * `expectedSeeds` and `expectedBenchmark` come from `BenchmarkManifest`, not from the bundle.
 * Passing the bundle's own values would make §56.3 a check a robot performs on itself, which is
 * the shape of every problem in §56.1.
 */
export function classify(
  bundle: RunBundle,
  expectedBenchmark: string,
  expectedSeeds: readonly string[],
): Classified {
  const reasons: ProvenanceReason[] = []

  // §56.4, first because it is the one observation that never changes the class. Collected up
  // front so the reason list reads in the order a person would ask the questions.
  if (bundle.blackbox_segment === null || bundle.blackbox_segment === undefined) {
    reasons.push({ code: 'not_replayable', subjects: [] })
  }

  if (bundle.device_signature !== 'verified') {
    reasons.push({ code: 'device_signature', subjects: [bundle.device_signature] })
  } else if (!bundle.device_known) {
    reasons.push({ code: 'device_unknown', subjects: [] })
  }

  if (bundle.benchmark_digest !== expectedBenchmark) {
    reasons.push({
      code: 'benchmark_mismatch',
      subjects: [expectedBenchmark, bundle.benchmark_digest],
    })
  }

  // Order and membership both. Two runs over the same seeds in a different order are two different
  // sequences of episodes, and a benchmark that fixes its seeds is fixing the sequence.
  if (!sameSeeds(bundle.seeds, expectedSeeds)) {
    reasons.push({
      code: 'seeds_not_supplied',
      subjects: [String(expectedSeeds.length), String(bundle.seeds.length)],
    })
  }

  if (bundle.simulator) {
    reasons.push({ code: 'simulator_declared', subjects: [] })
  } else {
    if (!bundle.birth_attested) reasons.push({ code: 'birth_unattested', subjects: [] })
    if (!bundle.image_attested) reasons.push({ code: 'image_unattested', subjects: [] })
  }

  // The order of these two branches is the anti-gaming argument, and it is the one thing in this
  // file that must not be rearranged for tidiness.
  //
  // A bundle nobody can attribute is `unattested` **before** its simulator flag is consulted,
  // because that flag is one of its own claims. And a *declared* simulator is `simulated` even
  // when everything else about it is perfect, because the one result this scheme exists to prevent
  // is a simulator on the field leaderboard.
  const attributable = bundle.device_signature === 'verified' && bundle.device_known

  const provenance: Provenance = !attributable
    ? 'unattested'
    : bundle.simulator
      ? 'simulated'
      : reasons.some(blocksField)
        ? 'unattested'
        : 'field'

  return { class: provenance, reasons }
}

/**
 * Whether two roll-ups of the same run agree (§56.5).
 *
 * > Roll-up per `BenchmarkManifest.scoring` runs on the robot — so an offline robot sees its own
 * > score — and again on the Hub from the raw per-episode outcomes. **The Hub's number is
 * > authoritative.** They must agree, and a disagreement is a defect worth investigating rather
 * > than a rounding difference to paper over.
 *
 * So this is an equality test with a tolerance, and the tolerance exists only for the floating
 * point representation rather than for the arithmetic: `1e-9`, which no genuine scoring difference
 * can hide under. A caller tempted to widen it is a caller papering over the divergence §31.4
 * exists to catch.
 */
export function scoresAgree(onRobot: number, onHub: number): boolean {
  // A non-finite score is not a score, and two of them are not an agreement. Returning true for
  // `NaN === NaN` would report a robot and a Hub that both failed to compute anything as being in
  // perfect accord.
  if (!Number.isFinite(onRobot) || !Number.isFinite(onHub)) return false
  return Math.abs(onRobot - onHub) <= 1e-9
}

/** The sentence for a disagreement (§56.5). */
export function explainDisagreement(onRobot: number, onHub: number): string {
  // Template interpolation is ECMAScript `ToString(Number)`, which is the spelling Rust's
  // `number_text` exists to reproduce. Nothing to import: this side is the definition.
  return `The robot rolled this run up to ${onRobot} and the Hub to ${onHub}. The Hub's `
    + `number is authoritative, and the difference is a defect `
    + 'rather than a rounding artefact: both sides run the same scoring contract over the same '
    + 'per-episode outcomes, so they disagreeing means the implementations diverged — which is '
    + 'precisely what the conformance corpus (§31.4) exists to catch.'
}
