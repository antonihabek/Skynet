"""Who makes each robot the sweep reaches, what it is, and what in this tree would drive the real one.

Written by hand, because none of it is in the files: a URDF names its links and joints and not its
maker, and nothing in a description says which driver speaks to the machine it describes. Each entry
is `description: (maker, model, class, route)`.

* **description** — the catalogue's own name for the file: a `robot_descriptions` module, a path in
  DeepMind's menagerie, or a description this repository ships.
* **class** — `humanoid`, `quadruped`, `biped`, `arm`, `dual_arm`, `mobile_manipulator`, `wheeled`,
  `hand`, `aerial` or `educational`. It decides the base a floating file is declared with (§5's
  `base`), and nothing else.
* **route** — the directory under `drivers/` whose driver speaks this robot's own interface, with
  the body name when the driver hosts several, or `None`. A route is a claim about *this tree*, and
  `tools/check-fleet.mjs` holds each one to `drivers/models.json`: the stage printed beside a robot is
  read from the manifest, never written here, so this file can never promote a driver.

A robot with two descriptions — a URDF from the maker and an MJCF from the menagerie — is one robot
with two rows, and the report counts both: two independent descriptions of one machine agreeing is
worth more than one.
"""

