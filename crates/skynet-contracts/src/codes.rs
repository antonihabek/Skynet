//! The error-code catalog: every machine-readable code, explained (§64).
//!
//! §64's rule is that a refusal names its fix, and the CLI obeys it at every emission site — but
//! an operator meeting a code second-hand (in a log, a bundle, a vendor's ticket) has nowhere to
//! look it up. This module is that place: one entry per code the system can emit, each with what
//! it means and what to do, served by `skynet explain` and printed as `docs/error-codes.md`.
//!
//! # Coverage, and how it stays complete
//!
//! The catalog has five sources, and the tests below pin four of them structurally:
//!
//! * the SCTS suite ([`crate::certification::SCTS_TESTS`]) — every test id, with its `measures`
//!   text transcribed verbatim (the test asserts the transcription, so a typo fails loudly);
//! * the domain tables (`PACKAGE_REJECTION_CODES`, `TRANSPORT_WARNING_CODES`,
//!   `POWER_FAULT_CODES`, `PROVENANCE_REASON_CODES`, `MOTION_FAULT_CODES`,
//!   `FRAME_REFUSAL_CODES`, `CODE_FAULTS`, birth `FINDINGS`) — every spelling;
//! * the workstation skill checks (`skill_check::SKILL_CHECK_IDS`) — pinned from the CLI crate,
//!   which is the direction the dependency runs;
//! * the API refusals ([`API_REFUSAL_CODES`]) — every spelling, pinned here and at the emission
//!   sites in `skynetd-io`, which scans its own sources against this table;
//! * the kernel's [`notices`](crate::codes#kernel-notices) — hand-pinned, because the kernel
//!   takes no dependencies and the catalog cannot enumerate what it cannot name. The kernel
//!   carries a tripwire test pinning its own spellings; if it fires, update the entries below.
//!
//! Meanings transcribe the defining documentation; actions derive from it. Where the definition
//! cites a section, the entry carries it — otherwise the domain's section, never a guess.

/// What kind of code this is: where it is emitted and what it asks of its reader.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CodeKind {
    /// An SCTS conformance test id, or a workstation check id in the same shape.
    Check,
    /// A transport plan warning: the plan runs, with the caveat named.
    Warning,
    /// Something measured wrong: power, motion list, pairing input, birth findings.
    Fault,
    /// Something was refused: admission, the frame pool, an API request, pairing, a skill
    /// invocation. The detail names the fix; the code names the failure for matching.
    Refusal,
    /// A provenance classification reason: why a bundle is not what it might have been.
    Reason,
    /// A kernel safety notice: read before running.
    Notice,
    /// A birth-certificate finding: what the document fails to establish.
    Finding,
}

/// One catalogued code.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CodeEntry {
    /// The wire spelling, exactly as emitted.
    pub code: &'static str,
    /// Which family it belongs to.
    pub kind: CodeKind,
    /// What it means, transcribed from the defining documentation.
    pub meaning: &'static str,
    /// What to do about it.
    pub action: &'static str,
    /// The specification section behind it.
    pub spec: &'static str,
}

/// Look a code up. Exact match only: a near-miss that explained itself as the wrong code
/// would be the vocabulary guessing, which §5.1 forbids roles and this forbids codes.
/// Suggestions live in the CLI, next to the keyboard.
pub fn lookup(code: &str) -> Option<&'static CodeEntry> {
    ALL.iter().find(|entry| entry.code == code)
}

