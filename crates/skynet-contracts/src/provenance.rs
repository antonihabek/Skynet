    #[test]
    fn every_reason_code_is_reachable_from_a_variant() {
        // The corpus holds the other vocabularies to their editions. This one has no reference to
        // be held against yet, so it is held to its own enumeration here instead — a code nobody
        // produces and a variant nobody lists are the two ways this list rots.
        let produced: Vec<&str> = vec![
            Reason::DeviceSignature(SignatureState::Absent).code(),
            Reason::DeviceUnknown.code(),
            Reason::SimulatorDeclared.code(),
            Reason::BirthUnattested.code(),
            Reason::ImageUnattested.code(),
            Reason::SeedsNotSupplied {
                expected: Vec::new(),
                used: Vec::new(),
            }
            .code(),
            Reason::BenchmarkMismatch {
                expected: String::new(),
                used: String::new(),
            }
            .code(),
            Reason::NotReplayable.code(),
        ];
        for code in PROVENANCE_REASON_CODES {
            assert!(
                produced.contains(&code),
                "{code} is listed and no variant produces it"
            );
        }
        for code in &produced {
            assert!(
                PROVENANCE_REASON_CODES.contains(code),
                "{code} is produced and is not listed"
            );
        }
        assert_eq!(produced.len(), PROVENANCE_REASON_CODES.len());
    }

