//! `skynet explain <code>...` — the catalog at the keyboard (§64).
//!
//! §64's rule is that a refusal names its fix, and it does — at the emission site. This command
//! is for the operator meeting a code second-hand: in a log line, a doctor bundle, a vendor's
//! ticket. Exact match only, like [`skynet_contracts::codes::lookup`]: a near-miss that explained
//! itself as the wrong code would be the vocabulary guessing. An unknown code lists its
//! same-domain neighbours instead, which teaches the spelling without asserting it.
//!
//! `--dump` prints `docs/error-codes.md`, and the CLI suite asserts the checked-in file matches
//! byte for byte — the document is generated, never hand-edited, so prose and catalog cannot
//! drift.

use crate::term;
use skynet_contracts::codes::{self, CodeKind};

pub const USAGE: &str = "\
skynet explain <code>...          What a finding, fault, refusal, warning, reason or notice means (§64)

  explain rhal.state.rate        The code, what it means, what to do, the section behind it
  explain --dump                 Print docs/error-codes.md; the suite pins the file to this output

  Unknown codes list their same-domain neighbours. Exit code is 1 if any argument is unknown.\
";

/// Render one entry the way the terminal shows it.
fn render(code: &str) -> Option<String> {
    let entry = codes::lookup(code)?;
    let kind = match entry.kind {
        CodeKind::Check => "check",
        CodeKind::Warning => "warning",
        CodeKind::Fault => "fault",
        CodeKind::Refusal => "refusal",
        CodeKind::Reason => "reason",
        CodeKind::Notice => "notice",
        CodeKind::Finding => "finding",
    };
    Some(format!(
        "{code}  [{kind}] ({})\n  {}\n  Next: {}",
        entry.spec, entry.meaning, entry.action
    ))
}

/// Same-domain neighbours of an unknown code, in catalog order, at most five. Dotted codes
/// share their first segment; undotted ones share nothing, so a fragment narrower than a
/// full code matches by prefix instead.
fn suggest(fragment: &str) -> Vec<&'static str> {
    let mut out: Vec<&'static str> = Vec::new();
    for entry in codes::ALL {
        if out.len() >= 5 {
            break;
        }
        if entry.code == fragment {
            continue;
        }
        if entry.code.starts_with(fragment) {
            out.push(entry.code);
        } else if fragment.contains('.') {
            let domain = fragment.split('.').next().unwrap_or(fragment);
            if entry.code.starts_with(&format!("{domain}.")) {
                out.push(entry.code);
            }
        } else if entry.code.contains(fragment) {
            out.push(entry.code);
        }
    }
    out
}

/// The whole catalog as `docs/error-codes.md`. Byte-stable by construction: catalog order,
/// no timestamps, no counts outside the entries themselves.
pub fn dump_docs() -> String {
    let mut page = String::from(
        "# Error codes\n\nEvery machine-readable code the system can emit, and what to do about \
         each. Generated by `skynet explain --dump` — the CLI suite asserts this file matches \
         that output byte for byte, so edit the catalog (`skynet-contracts/src/codes.rs`), \
         never this page.\n",
    );
    for entry in codes::ALL {
        let kind = match entry.kind {
            CodeKind::Check => "check",
            CodeKind::Warning => "warning",
            CodeKind::Fault => "fault",
            CodeKind::Refusal => "refusal",
            CodeKind::Reason => "reason",
            CodeKind::Notice => "notice",
            CodeKind::Finding => "finding",
        };
        page.push_str(&format!(
            "\n## `{}`\n\n*{}, {}.* {}\n\nNext: {}\n",
            entry.code, kind, entry.spec, entry.meaning, entry.action
        ));
    }
    page
}

pub fn run(rest: &[String]) -> i32 {
    if rest.iter().any(|arg| arg == "--dump") {
        print!("{}", dump_docs());
        return 0;
    }
    if rest.is_empty() || rest.iter().any(|arg| arg == "--help" || arg == "-h") {
        println!("{USAGE}");
        return 0;
    }
    let mut failed = false;
    for raw in rest {
        match render(raw) {
            Some(text) => println!("{text}"),
            None => {
                failed = true;
                println!("{raw}  {}", term::dim("is not a code this system emits"));
                let neighbours = suggest(raw);
                if !neighbours.is_empty() {
                    println!("  {}: {}", term::dim("did you mean"), neighbours.join(", "));
                }
            }
        }
    }
    i32::from(failed)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_codes_render_with_meaning_action_and_section() {
        let text = render("rhal.state.rate").expect("SCTS codes render");
        assert!(text.contains("rhal.state.rate"));
        assert!(text.contains("[check]"));
        assert!(text.contains("Next: "));
        assert!(text.contains("§15"));
        let refusal = render("digest_mismatch").expect("domain codes render");
        assert!(refusal.contains("[refusal]"));
    }

    #[test]
    fn unknown_codes_suggest_their_domain_and_fail() {
        assert_eq!(run(&["rhal.no_such_check".to_string()]), 1);
        let neighbours = suggest("rhal.no_such_check");
        assert!(!neighbours.is_empty());
        assert!(neighbours.iter().all(|code| code.starts_with("rhal.")));
        // One failure among successes still fails.
        assert_eq!(
            run(&["unsigned".to_string(), "no_such_code".to_string()]),
            1
        );
    }

    #[test]
    fn dump_is_deterministic_and_covers_the_catalog() {
        let first = dump_docs();
        let second = dump_docs();
        assert_eq!(first, second);
        for entry in codes::ALL {
            assert!(
                first.contains(entry.code),
                "{} is missing from the dump",
                entry.code
            );
        }
    }
}
