unsafe extern "C" fn open(_config_json: *const c_char, out: *mut *mut Ctx) -> i32 {{
    // TODO: read your bus address, baud rate or interface name out of the configuration JSON.
    if out.is_null() {{
        return status::EINVAL;
    }}
    BODY.open.store(true, Ordering::Release);
    BODY.estop.store(false, Ordering::Release);
    BODY.seq.store(0, Ordering::Release);
    BODY.clock_ns.store(1, Ordering::Release);

    // TODO: open the bus, enable the drives, and fail here rather than later if anything is silent.

    // The context pointer is opaque to the OS; a static body needs no allocation behind it.
    unsafe {{ *out = &BODY as *const Body as *mut Ctx }};
    status::OK
}}

unsafe extern "C" fn close(ctx: *mut Ctx) -> i32 {{
    if ctx.is_null() {{
        return status::EINVAL;
    }}
    // TODO: disable the drives and release the bus. Leaving a robot enabled after close is how a
    // crashed process leaves a live machine.
    BODY.open.store(false, Ordering::Release);
    status::OK
}}

/// Real-time path: wait-free, no allocation, respects the deadline.
unsafe extern "C" fn read_state(ctx: *mut Ctx, out: *mut State, _deadline_ns: u64) -> i32 {{
    if ctx.is_null() || out.is_null() {{
        return status::EINVAL;
    }}
    if !BODY.open.load(Ordering::Acquire) {{
        return status::EPERM;
    }}

    // TODO: read the bus. Return status::ETIMEDOUT when it does not answer before the deadline —
    // "the bus timed out" and "the drive is faulted" lead to completely different investigations,
    // and the black box records which one it was.
    let seq = BODY.seq.fetch_add(1, Ordering::AcqRel) + 1;
    let stamp = BODY.clock_ns.fetch_add(1_000_000, Ordering::AcqRel) + 1_000_000;

    // SAFETY: the OS passes a valid `State` whose three arrays are at least `joint_count` long.
    let state = unsafe {{ &mut *out }};
    // Stamped at ACQUISITION, never at return: a timestamp applied on return folds this driver's
    // own latency into every downstream budget.
    state.stamp_ns = stamp;
    state.seq = seq;
    state.joint_count = JOINTS as u16;
    state.flags = if BODY.estop.load(Ordering::Acquire) {{
        flags::ESTOP
    }} else {{
        0
    }};
    state.base_pose = [f32::NAN; 7]; // not localised
    state.base_twist = [0.0; 6];
    state.fault_code = 0;

    for joint in 0..JOINTS {{
        if !state.position_rad.is_null() {{
            // SAFETY: the OS guarantees `joint_count` elements, and `joint < JOINTS`.
            unsafe {{ *state.position_rad.add(joint) = 0.0 }};
        }}
        // NaN is the honest value for something this body does not measure. Zero is a measurement.
        if !state.velocity_rad_s.is_null() {{
            unsafe {{ *state.velocity_rad_s.add(joint) = f32::NAN }};
        }}
        if !state.effort_nm.is_null() {{
            unsafe {{ *state.effort_nm.add(joint) = f32::NAN }};
        }}
    }}
    status::OK
}}

unsafe extern "C" fn write_command(ctx: *mut Ctx, cmd: *const Command, _deadline_ns: u64) -> i32 {{
    if ctx.is_null() || cmd.is_null() {{
        return status::EINVAL;
    }}
    if !BODY.open.load(Ordering::Acquire) {{
        return status::EPERM;
    }}
    // SAFETY: non-null, and the OS keeps it alive for the duration of the call.
    let command = unsafe {{ &*cmd }};

    // Shape first, and refuse rather than clamp: a driver that accepts a short command is one that
    // reads past the end of the caller's array.
    if command.joint_count as usize != JOINTS || command.values.is_null() || command.mask.is_null()
    {{
        return status::EINVAL;
    }}
    if Mode::from_u8(command.mode).is_none() {{
        return status::EINVAL;
    }}
    // TODO: refuse the modes this body does not actually accept, and keep `control_modes` in the
    // descriptor agreeing with whatever you decide here.
    if BODY.estop.load(Ordering::Acquire) {{
        return status::EPERM;
    }}

    for joint in 0..JOINTS {{
        // SAFETY: `joint_count` was checked to equal JOINTS, and both arrays are that long.
        let apply = unsafe {{ *command.mask.add(joint) }} != 0;
        // A zero mask means HOLD, not zero. On a torque-controlled joint that is the difference
        // between holding position and going limp.
        if !apply {{
            continue;
        }}
        let value = unsafe {{ *command.values.add(joint) }};
        if !value.is_finite() {{
            return status::EINVAL;
        }}
        // TODO: write `value` to the drive.
    }}
    status::OK
}}

/// Callable from a signal handler and from a dying process. No allocation, no locks, no blocking.
unsafe extern "C" fn emergency_stop(ctx: *mut Ctx) -> i32 {{
    if ctx.is_null() {{
        return status::EINVAL;
    }}
    BODY.estop.store(true, Ordering::Release);
    // TODO: assert the hardware stop. A flag alone stops nothing — it only makes the stop
    // observable, which is what `safety.estop.latency` measures on the bench.
    status::OK
}}

unsafe extern "C" fn describe(ctx: *mut Ctx, json_out: *mut c_char, len: usize) -> i32 {{
    if ctx.is_null() || json_out.is_null() {{
        return status::EINVAL;
    }}
    let bytes = DESCRIPTOR.as_bytes();
    // Too small is an error, never a truncation: half a parsed body description is worse than a
    // failed one, and the OS retries with a larger buffer.
    if len < bytes.len() + 1 {{
        return status::EINVAL;
    }}
    // SAFETY: `json_out` is writable for `len` bytes and `len > bytes.len()`.
    unsafe {{
        std::ptr::copy_nonoverlapping(bytes.as_ptr() as *const c_char, json_out, bytes.len());
        *json_out.add(bytes.len()) = 0;
    }}
    bytes.len() as i32
}}

