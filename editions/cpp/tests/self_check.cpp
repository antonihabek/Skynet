// The C++ edition's own checks — what the corpus structurally cannot reach.
//
//     make test                       # from editions/cpp
//     build/self_check <edition-root> # the directory holding src/ and include/
//
// Four kinds, and each is here because the corpus cannot be:
//
// 1. **The runner's accounting.** It is the only thing that says how far this edition has got, and
//    it has four buckets rather than two — passed, failed, no handler, declined. A miscount is worse
//    than a failing case: a failing case is loud, and a number that quietly reads a hundred
//    untranscribed cases as a hundred wrong answers, or the reverse, is a green run that means
//    nothing. So it is run over synthetic corpora with known answers.
// 2. **The case tables.** `src/unicode_case.inc` maps single code points, and a table cannot be wrong
//    about a string; the code that walks a string with it, and applies `toLowerCase`'s final-sigma
//    rule, can. `tests/case_vectors.inc` holds whole strings the reference's engine converted, drawn
//    from all four classes that rule tells apart. Both files come from `tools/unicode-case.ts`.
// 3. **The JavaScript helpers, at their edges.** Each is the transcription of one expression, and
//    each has one input where the obvious C++ gives a different answer. The corpus reaches some of
//    those inputs by luck; this reaches them on purpose.
// 4. **The source.** `std::tolower` and its family consult the process locale, so a Turkish locale
//    would classify a role differently on one workstation than on another. Nothing in `src/` may
//    call them — a gate on the spelling, because the corpus cannot vary the locale.
//
// The exit status is the number of failed checks, capped, so a CI step goes red on any of them.

#include "skynet_os/corpus.hpp"
#include "skynet_os/js.hpp"
#include "skynet_os/json.hpp"

#include <cmath>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <limits>
#include <sstream>
#include <string>
#include <string_view>
#include <vector>

namespace {

struct CaseVector {
  bool upper;
  std::u32string_view input;
  std::u32string_view expected;
};

// `kCaseVectors` and `kVectorsUnicodeVersion`, generated by `tools/unicode-case.ts`.
#include "case_vectors.inc"

int checked = 0;
int failed = 0;

void check(const std::string& name, bool condition, const std::string& detail = "") {
  ++checked;
  if (condition) {
    std::printf("  ok    %s\n", name.c_str());
    return;
  }
  ++failed;
  std::printf("  FAIL  %s%s%s\n", name.c_str(), detail.empty() ? "" : " - ", detail.c_str());
}

std::string hex_of(std::u32string_view value) {
  std::string out;
  char buffer[16];
  for (const char32_t code_point : value) {
    std::snprintf(buffer, sizeof buffer, "%s%04X", out.empty() ? "" : " ", static_cast<unsigned>(code_point));
    out += buffer;
  }
  return out;
}

skynet::Case make_case(std::string id, skynet::Json input, std::string expected) {
  return skynet::Case{std::move(id), "", std::move(input), std::move(expected)};
}

// ── 1. The runner's accounting ───────────────────────────────────────────────

void runner_accounting() {
  std::printf("\nthe runner's accounting\n");

  skynet::Json role = skynet::Json::object();
  role.set("role", skynet::Json::string("left_arm.shoulder.pitch"));
  const std::string right = skynet::dispatch("roles", "vocabulary", role).canonical();

  std::vector<skynet::CorpusFile> files;
  // A kind that answers: one case right and one wrong.
  files.push_back({"roles/vocabulary.json", "roles", "vocabulary",
                   {make_case("right", role, right), make_case("wrong", role, "\"something else\"")}});
  // A kind with no handler at all, three cases.
  files.push_back({"unheard-of/only.json", "unheard-of", "only",
                   {make_case("a", skynet::Json::object(), "1"), make_case("b", skynet::Json::object(), "2"),
                    make_case("c", skynet::Json::object(), "3")}});
  // A kind that exists and declines a whole file by name, two cases.
  files.push_back({"ota/not-a-file.json", "ota", "not-a-file",
                   {make_case("a", skynet::Json::object(), "1"), make_case("b", skynet::Json::object(), "2")}});

  const skynet::Report report = skynet::run_corpus(files);
  const auto has = [](const std::vector<std::string>& list, const std::string& item) {
    for (const std::string& one : list) {
      if (one == item) return true;
    }
    return false;
  };

  check("a right answer is counted as passed", report.passed == 1, "passed=" + std::to_string(report.passed));
  check("a wrong answer is counted as failed, and described", report.failed == 1 && report.failures.size() == 1,
        "failed=" + std::to_string(report.failed));
  check("a kind with no handler counts every case it holds, and is named",
        report.no_handler_cases == 3 && has(report.missing_handlers, "unheard-of"),
        "no_handler_cases=" + std::to_string(report.no_handler_cases));
  check("a declined file is not implemented rather than failed, and is named",
        report.declined_cases == 2 && has(report.declined_files, "ota/not-a-file"),
        "declined_cases=" + std::to_string(report.declined_cases));
  check("the total is every case, in exactly one bucket", report.total() == 7,
        "total=" + std::to_string(report.total()));
  check("a kind with a failure is not complete, and a kind with a declined file is partial",
        !has(report.complete, "roles") && !has(report.complete, "ota") && has(report.partial, "ota"));

  // The other half of the declined-file rule: the same kind becomes complete once the declining file
  // is gone, so the check above is passing because of the rule and not for some other reason.
  const skynet::Report alone = skynet::run_corpus({{"roles/vocabulary.json", "roles", "vocabulary",
                                                    {make_case("right", role, right)}}});
  check("...and a kind whose every case passes is complete", has(alone.complete, "roles"));
}

// ── 2. The case tables ───────────────────────────────────────────────────────

void case_vectors() {
  std::printf("\nthe case tables, against the engine the reference runs on\n");

  check("the tables and the vectors were generated under one Unicode version",
        skynet::js::unicode_version() == kVectorsUnicodeVersion,
        std::string(skynet::js::unicode_version()) + " vs " + std::string(kVectorsUnicodeVersion));

  int mismatched = 0;
  std::string first;
  for (const CaseVector& vector : kCaseVectors) {
    const std::u32string input(vector.input);
    const std::u32string produced = vector.upper ? skynet::js::to_upper(input) : skynet::js::to_lower(input);
    if (produced != vector.expected) {
      if (mismatched == 0) {
        first = std::string(vector.upper ? "toUpperCase" : "toLowerCase") + " of [" + hex_of(vector.input) +
                "] gave [" + hex_of(produced) + "], the engine gave [" + hex_of(vector.expected) + "]";
      }
      ++mismatched;
    }
  }
  check(std::to_string(sizeof kCaseVectors / sizeof kCaseVectors[0]) +
            " whole strings convert as the engine converted them",
        mismatched == 0, first);

  // The two a corpus case already holds, as UTF-8, so a regression names itself here as well.
  check("the sharp s upper-cases to two letters", skynet::js::to_upper("\xC3\x9F") == "SS");
  check("the Kelvin sign lower-cases to ASCII k", skynet::js::to_lower("\xE2\x84\xAA") == "k");
}

// ── 3. The JavaScript helpers, at their edges ────────────────────────────────

void helpers() {
  std::printf("\nthe JavaScript helpers, at the inputs where C++ disagrees\n");

  // `Math.round` rounds ties toward +infinity, on the value itself.
  check("Math.round(0.49999999999999994) is 0, where floor(x + 0.5) says 1",
        skynet::js::math_round(0.49999999999999994) == 0);
  check("Math.round(-2.5) is -2, where a half-away rounding says -3", skynet::js::math_round(-2.5) == -2);
  check("Math.round(2.5) is 3", skynet::js::math_round(2.5) == 3);

  // `trim()`'s set: the byte-order mark goes, U+0085 and U+001C stay.
  check("trim() removes a byte-order mark and a no-break space",
        skynet::js::trim("\xEF\xBB\xBF\xC2\xA0x\xC2\xA0\xEF\xBB\xBF") == "x");
  check("trim() keeps U+0085 and U+001C", skynet::js::trim("\xC2\x85x\x1C") == "\xC2\x85x\x1C");
  check("\\s is the same set, one character at a time",
        skynet::js::space_at("\xEF\xBB\xBF", 0) == 3 && skynet::js::space_at("\xC2\x85", 0) == 0);

  // Truthiness: an empty object is truthy, the string "0" is truthy, the number 0 is not.
  check("an empty object and the string \"0\" are truthy, and 0 is not",
        skynet::js::truthy(skynet::Json::object()) && skynet::js::truthy(skynet::Json::string("0")) &&
            !skynet::js::truthy(skynet::Json::number(0)));

  // `?? fallback` over a bare number: absent takes the fallback, and a null is the NaN it stands for.
  skynet::Json holder = skynet::Json::object();
  holder.set("present", skynet::Json::null());
  check("a bare number that is null is NaN, and one that is absent is the fallback",
        std::isnan(skynet::js::bare_number(holder, "present", 5)) &&
            skynet::js::bare_number(holder, "absent", 5) == 5);
}

// ── 4. The source ────────────────────────────────────────────────────────────

void source(const std::filesystem::path& root) {
  std::printf("\nthe source, for calls the corpus cannot catch\n");

  const std::filesystem::path src = root / "src";
  // A scan that looked in the wrong place finds nothing and says so as a pass. Refuse instead.
  if (!std::filesystem::exists(src / "js.cpp")) {
    check("the source directory was found", false, "no src/js.cpp under " + root.string());
    return;
  }

  static const std::vector<std::string> kRefused = {
      "std::tolower", "std::toupper", "std::isspace", "std::isdigit", "std::isalpha",
      "std::isalnum", "std::islower", "std::isupper", "std::isxdigit", "std::regex", "<cctype>", "<locale>",
  };
  std::vector<std::string> found;
  int scanned = 0;
  for (const auto& entry : std::filesystem::recursive_directory_iterator(src)) {
    const std::string extension = entry.path().extension().string();
    if (!entry.is_regular_file() || (extension != ".cpp" && extension != ".inc")) {
      continue;
    }
    ++scanned;
    std::ifstream file(entry.path());
    std::string line;
    int number = 0;
    while (std::getline(file, line)) {
      ++number;
      // A comment may name what it refuses; only code is scanned.
      const std::size_t comment = line.find("//");
      const std::string code = comment == std::string::npos ? line : line.substr(0, comment);
      for (const std::string& word : kRefused) {
        if (code.find(word) != std::string::npos) {
          found.push_back(entry.path().filename().string() + ":" + std::to_string(number) + " " + word);
        }
      }
    }
  }

  std::string listed;
  for (const std::string& one : found) listed += (listed.empty() ? "" : ", ") + one;
  check("no file in src/ calls a locale-dependent classifier (" + std::to_string(scanned) + " files scanned)",
        found.empty() && scanned > 0, listed);
}

}  // namespace

int main(int argc, char** argv) {
  const std::filesystem::path root = argc > 1 ? argv[1] : ".";

  runner_accounting();
  case_vectors();
  helpers();
  source(root);

  std::printf("\n");
  if (failed > 0) {
    std::printf("self-check FAILED - %d of %d\n", failed, checked);
    return failed > 100 ? 100 : failed;
  }
  std::printf("self-check ok - %d checks\n", checked);
  return 0;
}
