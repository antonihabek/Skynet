// Run provenance (§56).
//
// Pure: no clock, no key, no database. The device signature arrives **decided**, and whether the
// Hub recognises the device is a boolean the Hub supplies. That is what lets the Hub classify a
// submitted bundle and a robot predict its own class offline, by one function.

// ProvenanceReason is why a bundle is not what it might have been.
//
// `Subjects` carries whatever the reason is about, and the ordering rule is birth's: **what was
// expected, then what was supplied**, never the reverse.
type ProvenanceReason struct {
	Code     string
	Subjects []string
}

// Rankable reports whether a result of this class appears on a leaderboard at all.
func Rankable(provenance string) bool {
	return provenance == "field" || provenance == "simulated"
}

// RankedSeparately reports whether it is ranked in its own table rather than against field results.
//
// §56.2 says *"eligible, separately ranked"* and the separation is not a courtesy. A simulated run
// and a field run are not comparable numbers, and putting them in one table would make the
// leaderboard a worse instrument than no leaderboard.
func RankedSeparately(provenance string) bool { return provenance == "simulated" }

// BlocksField reports whether this reason is why the bundle cannot be `field`.
//
// Everything except `not_replayable`: a result can be perfectly attested and unreplayable.
func BlocksField(reason ProvenanceReason) bool { return reason.Code != "not_replayable" }

// ExplainProvenance is the sentence a publisher gets.
func ExplainProvenance(reason ProvenanceReason) string {
	switch reason.Code {
	case "device_signature":
		return "The device's signature over this bundle is " + subject(reason, 0) + ", so nothing " +
			"in it is attributable to a machine. The result is recorded and is not ranked: a number " +
			"nobody can attribute is not evidence, which is the whole of §56.1."
	case "device_unknown":
		return "The signature verifies and this Hub does not know the device that made it. Nothing " +
			"is wrong with the bytes; what is missing is a registered machine to attribute them to. " +
			"Register the device, then re-submit."
	case "simulator_declared":
		return "The RHAL driver declared itself a simulator (§35.3), so this is a simulated result " +
			"and is ranked on the simulated table. This is the driver meeting its obligation rather " +
			"than a fault — and a simulated run and a field run are not comparable numbers, which " +
			"is why the tables are separate."
	case "birth_unattested":
		return "This robot's birth certificate does not attest it (§50), so \"a real robot of this " +
			"model with these joint ratings\" is a claim the machine makes about itself. The result " +
			"is recorded and not ranked as a field result."
	case "image_unattested":
		return "The OS image running during this evaluation was not attested, so what produced " +
			"these numbers is not established. Recorded, not ranked as a field result."
	case "seeds_not_supplied":
		// The counts rather than the seeds: a benchmark can carry hundreds, and a sentence that
		// pasted both lists would be one nobody reads.
		return "This run used seeds the benchmark did not supply (" + subject(reason, 0) + " given, " +
			subject(reason, 1) + " used). §56.3: seeds come from the benchmark and are never " +
			"generated by the robot, because a robot that picks its own seeds picks easy ones — and " +
			"it need not do so dishonestly for the number to be worthless. This is not a run of that " +
			"benchmark."
	case "benchmark_mismatch":
		return "This bundle is a run of benchmark " + subject(reason, 1) + " and is being ranked " +
			"against " + subject(reason, 0) + ". Two benchmarks are two questions, and a score " +
			"against one says nothing about the other."
	case "not_replayable":
		return "No black box segment accompanies this run, so a disputed result cannot be replayed " +
			"(§56.4). The class is unaffected — a result can be perfectly attested and unreplayable " +
			"— but a number with a recording behind it is a different class of claim from a number " +
			"in a table."
	}
	return ""
}

// subject is the reference's `reason.subjects[n] ?? ""`: an index past the end is the empty string
// rather than a panic, which is what indexing a JavaScript array out of range gives.
func subject(reason ProvenanceReason, at int) string {
	if at < 0 || at >= len(reason.Subjects) {
		return ""
	}
	return reason.Subjects[at]
}

// Classified is what classifying one bundle concluded.
type Classified struct {
	Class   string
	Reasons []ProvenanceReason
}

// Replayable reports whether the run can be replayed from its recording (§56.4).
func Replayable(classified Classified) bool {
	for _, reason := range classified.Reasons {
		if reason.Code == "not_replayable" {
			return false
		}
	}
	return true
}

// ClassifyRun classifies a run bundle against the benchmark it claims to be a run of (§56.2).
//
// `expectedBenchmark` and `expectedSeeds` come from the benchmark manifest, not from the bundle.
// Passing the bundle's own values would make §56.3 a check a robot performs on itself, which is the
// shape of every problem in §56.1.
func ClassifyRun(bundle canonical.Value, expectedBenchmark string, expectedSeeds []string) Classified {
	reasons := []ProvenanceReason{}

	// §56.4, first because it is the one observation that never changes the class. Collected up
	// front so the reason list reads in the order a person would ask the questions.
	segment, hasSegment := bundle.Get("blackbox_segment")
	if !hasSegment || segment.IsNull() {
		reasons = append(reasons, ProvenanceReason{Code: "not_replayable", Subjects: []string{}})
	}

	signature, _ := bundle.Field("device_signature").Str()
	deviceKnown := isTrue(bundle.Field("device_known"))
	if signature != "verified" {
		reasons = append(reasons, ProvenanceReason{Code: "device_signature", Subjects: []string{signature}})
	} else if !deviceKnown {
		reasons = append(reasons, ProvenanceReason{Code: "device_unknown", Subjects: []string{}})
	}

	benchmark, _ := bundle.Field("benchmark_digest").Str()
	if benchmark != expectedBenchmark {
		reasons = append(reasons, ProvenanceReason{
			Code: "benchmark_mismatch", Subjects: []string{expectedBenchmark, benchmark},
		})
	}

	// Order and membership both. Two runs over the same seeds in a different order are two
	// different sequences of episodes, and a benchmark that fixes its seeds is fixing the sequence.
	seeds := stringsOf(bundle.Field("seeds"))
	if !sameSeeds(seeds, expectedSeeds) {
		reasons = append(reasons, ProvenanceReason{
			Code: "seeds_not_supplied",
			Subjects: []string{
				js.NumberToString(float64(len(expectedSeeds))),
				js.NumberToString(float64(len(seeds))),
			},
		})
	}

	simulator := isTrue(bundle.Field("simulator"))
	if simulator {
		reasons = append(reasons, ProvenanceReason{Code: "simulator_declared", Subjects: []string{}})
	} else {
		if !isTrue(bundle.Field("birth_attested")) {
			reasons = append(reasons, ProvenanceReason{Code: "birth_unattested", Subjects: []string{}})
		}
		if !isTrue(bundle.Field("image_attested")) {
			reasons = append(reasons, ProvenanceReason{Code: "image_unattested", Subjects: []string{}})
		}
	}

	// The order of these two branches is the anti-gaming argument, and it is the one thing here
	// that must not be rearranged for tidiness.
	//
	// A bundle nobody can attribute is `unattested` **before** its simulator flag is consulted,
	// because that flag is one of its own claims. And a *declared* simulator is `simulated` even
	// when everything else about it is perfect, because the one result this scheme exists to
	// prevent is a simulator on the field leaderboard.
	attributable := signature == "verified" && deviceKnown

	class := "field"
	switch {
	case !attributable:
		class = "unattested"
	case simulator:
		class = "simulated"
	default:
		for _, reason := range reasons {
			if BlocksField(reason) {
				class = "unattested"
				break
			}
		}
	}

	return Classified{Class: class, Reasons: reasons}
}

func sameSeeds(left []string, right []string) bool {
	if len(left) != len(right) {
		return false
	}
	for at := range left {
		if left[at] != right[at] {
			return false
		}
	}
	return true
}

func stringsOf(array canonical.Value) []string {
	out := make([]string, 0, array.Len())
	for _, entry := range array.Items() {
		text, _ := entry.Str()
		out = append(out, text)
	}
	return out
}

// ScoresAgree reports whether two roll-ups of the same run agree (§56.5).
//
// An equality test with a tolerance, and the tolerance exists only for the floating point
// representation rather than for the arithmetic: 1e-9, which no genuine scoring difference can hide
// under. A caller tempted to widen it is a caller papering over the divergence §31.4 exists to
// catch.
func ScoresAgree(onRobot, onHub float64) bool {
	// A non-finite score is not a score, and two of them are not an agreement. Returning true for
	// NaN == NaN would report a robot and a Hub that both failed to compute anything as being in
	// perfect accord.
	if !canonical.Finite(onRobot) || !canonical.Finite(onHub) {
		return false
	}
	return math.Abs(onRobot-onHub) <= 1e-9
}

// ExplainDisagreement is the sentence for a disagreement (§56.5).
func ExplainDisagreement(onRobot, onHub float64) string {
	// Template interpolation is ECMAScript ToString(Number), which is what js.NumberToString is
	// for — not the canonical writer, which would spell a very small or very large score
	// positionally where the reference spells it with an exponent.
	return "The robot rolled this run up to " + js.NumberToString(onRobot) + " and the Hub to " +
		js.NumberToString(onHub) + ". The Hub's number is authoritative, and the difference is a defect " +
		"rather than a rounding artefact: both sides run the same scoring contract over the same " +
		"per-episode outcomes, so they disagreeing means the implementations diverged — which is " +
		"precisely what the conformance corpus (§31.4) exists to catch."
}

// ── the corpus ──────────────────────────────────────────────────────────────

func provenanceClassify(input canonical.Value) (canonical.Value, error) {
	expectedBenchmark, _ := input.Field("expected_benchmark").Str()
	classified := ClassifyRun(
		input.Field("bundle"), expectedBenchmark, stringsOf(input.Field("expected_seeds")))

	reasons := canonical.Array()
	for _, reason := range classified.Reasons {
		reasons = reasons.Push(canonical.Object().
			Set("blocks_field", canonical.Bool(BlocksField(reason))).
			Set("code", canonical.String(reason.Code)).
			Set("message", canonical.String(ExplainProvenance(reason))).
			Set("subjects", canonical.Strings(reason.Subjects)))
	}
	return canonical.Object().
		Set("class", canonical.String(classified.Class)).
		Set("rankable", canonical.Bool(Rankable(classified.Class))).
		Set("ranked_separately", canonical.Bool(RankedSeparately(classified.Class))).
		Set("reasons", reasons).
		Set("replayable", canonical.Bool(Replayable(classified))), nil
}

func provenanceScores(input canonical.Value) (canonical.Value, error) {
	scores := input.Field("scores")
	// `scoresAgree(onRobot: number, onHub: number)` takes bare numbers, so corpus/README.md's
	// second reading applies: a `null` here is not a declared absence — no caller could have
	// supplied one — it is how the generator spelt a non-finite value, and it reads as NaN.
	// `provenance/scores :: two-robots-that-computed-nothing` is the case that failed a third
	// edition for reading the file exactly as it was written.
	onRobot, robotIsNumber := scores.Field("on_robot").Number()
	onHub, hubIsNumber := scores.Field("on_hub").Number()
	robot := js.BareNumber(true, onRobot, robotIsNumber)
	hub := js.BareNumber(true, onHub, hubIsNumber)

	agree := ScoresAgree(robot, hub)
	detail := canonical.Null()
	if !agree {
		detail = canonical.String(ExplainDisagreement(robot, hub))
	}
	return canonical.Object().
		Set("agree", canonical.Bool(agree)).
		Set("detail", detail), nil
}
