"""gen_codes.py HEADER OUT : the controller's message codes, from the maker's own table, as a Python module.

    python3 sim/gen_codes.py /path/to/rbpodo/include/rbpodo/error_code.hpp skynet_rainbow/codes.py

`error_code.hpp` is Rainbow Robotics' `rbpodo` (Apache-2.0, https://github.com/RainbowRobotics/rbpodo): `ErrorCodeMessage`, a table of the codes a controller reports as `error[code][N]`, `warn[code][N]` and `info[code][N]`, each with a Korean and an English
text. This writes the English, with the table's `\\n` line breaks turned into spaces, and nothing else: the table was generated, not typed, and `drivers/rainbow/layout_check.py` holds it to the table the maker's client carries.
"""
import re
import sys

source, out = sys.argv[1], sys.argv[2]
text = open(source, encoding="utf-8").read()
entries = re.findall(r'\{\s*(\d+),\s*\{R"\((.*?)\)",\s*R"\((.*?)\)"\}\s*\}', text, re.S)
codes: dict[int, str] = {}
for number, _korean, english in entries:
    assert int(number) not in codes, number
    codes[int(number)] = " ".join(english.replace("\\n", " ").replace("<br>", " ").split())
assert len(codes) == len(entries) and len(codes) > 500, len(codes)
with open(out, "w", encoding="utf-8", newline="\n") as handle:
    handle.write('"""The controller\'s message codes: `error[code][N]`, `warn[code][N]` and `info[code][N]`, with the English text of each, generated by `sim/gen_codes.py` from Rainbow Robotics\' own table (`rbpodo`\'s `error_code.hpp`,\n'
                 'Apache-2.0, https://github.com/RainbowRobotics/rbpodo). %d codes. Not edited by hand."""\n\nfrom __future__ import annotations\n\n' % len(codes))
    handle.write("CODES: dict[int, str] = {\n")
    for number in sorted(codes):
        handle.write(f"    {number}: {codes[number]!r},\n")
    handle.write("}\n")
print(len(codes), "codes ->", out)
